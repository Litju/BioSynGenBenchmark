"""RES-481: compare regenerated I0 artifacts with the frozen I0 run records.

The frozen files under runs/overnight/i0-queue-20261012 are never rewritten.
Regenerated bytes are compared in memory and the result is written to
runs/i1/res481/i0-regression.json.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

from scripts import generate_benchmark_report, generate_mechanics_fixture
from scripts import generate_observation_fixture
from scripts.run_pilot import build_run_artifacts


ROOT = Path(__file__).resolve().parents[1]
I0 = ROOT / "runs" / "overnight" / "i0-queue-20261012"
OUTPUT = ROOT / "runs" / "i1" / "res481" / "i0-regression.json"


def _sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _json_text(value: object) -> bytes:
    return (json.dumps(value, indent=2, sort_keys=True, allow_nan=False) + "\n").encode("utf-8")


def _diff_paths(old: object, new: object, path: str = "") -> list[str]:
    if isinstance(old, dict) and isinstance(new, dict):
        out: list[str] = []
        for key in sorted(set(old) | set(new)):
            out += _diff_paths(old.get(key), new.get(key), f"{path}/{key}")
        return out
    if isinstance(old, list) and isinstance(new, list) and len(old) == len(new):
        out = []
        for index, (a, b) in enumerate(zip(old, new)):
            out += _diff_paths(a, b, f"{path}[{index}]")
        return out
    return [] if old == new else [path]


def build() -> dict[str, object]:
    records: list[dict[str, object]] = []
    pilot = build_run_artifacts()
    for name, content in sorted(pilot.items()):
        frozen = (I0 / "end-to-end-run-a" / name).read_bytes()
        entry = {
            "artifact": f"end-to-end-run-a/{name}",
            "frozen_sha256": _sha(frozen),
            "regenerated_sha256": _sha(content),
            "identical": frozen == content,
        }
        if not entry["identical"] and name.endswith(".json"):
            entry["differing_json_paths"] = _diff_paths(
                json.loads(frozen), json.loads(content)
            )
        records.append(entry)
    for name, builder in (
        ("res476-mechanics-fixture.json", generate_mechanics_fixture.build_fixture),
        ("res477-observation-fixture.json", generate_observation_fixture.build_fixture),
        ("res478-benchmark-report.json", generate_benchmark_report.build_report),
    ):
        frozen_bytes = (I0 / name).read_bytes()
        regenerated = json.loads(json.dumps(builder(), sort_keys=True))
        frozen_value = json.loads(frozen_bytes)
        paths = _diff_paths(frozen_value, regenerated)
        records.append(
            {
                "artifact": name,
                "frozen_sha256": _sha(frozen_bytes),
                "regenerated_value_identical": not paths,
                "differing_json_paths": paths,
            }
        )
    return {
        "purpose": "RES-481 I0 baseline preservation check after P0 repairs",
        "frozen_root": "runs/overnight/i0-queue-20261012 (read only)",
        "records": records,
        "interpretation": (
            "manifest.json differs only in source_sha256 because repaired sources "
            "changed; res478 differs only in the reason text of the "
            "INVENTED_BILATERAL_FROM_COMBINED_FORCE finding (outcome and code identical)."
        ),
    }


def main() -> None:
    report = build()
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_bytes(_json_text(report))
    for record in report["records"]:
        same = record.get("identical", record.get("regenerated_value_identical"))
        detail = "" if same else f" differs at {record.get('differing_json_paths')}"
        print(f"{'IDENTICAL' if same else 'CHANGED  '} {record['artifact']}{detail}")
    print(f"Wrote {OUTPUT}")


if __name__ == "__main__":
    main()
