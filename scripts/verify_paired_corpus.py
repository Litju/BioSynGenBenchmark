def numbers(rows, fields, code):
    try:
        values = [[float(row[f]) for f in fields] for row in rows]
    except (KeyError, TypeError, ValueError):
        raise ReferenceRefused(code) from None
    require(all(math.isfinite(v) for row in values for v in row), code)
    return values


def finite_list(values, length=None, minimum=0):
    return (type(values) is list and len(values) >= minimum and (length is None or len(values) == length)
            and all(finite_number(v) for v in values))


def vector2(value):
    return finite_list(value, 2)


def body_vector(body):
    """Planar body state in submission order: x, z, angle, vx, vz, omega."""
    require(type(body) is dict and vector2(body.get("position_m")) and vector2(body.get("velocity_m_s")) and
            finite_number(body.get("angle_rad")) and finite_number(body.get("angular_velocity_rad_s")),
            "REFERENCE_STATES_MALFORMED")
    return [*body["position_m"], body["angle_rad"], *body["velocity_m_s"], body["angular_velocity_rad_s"]]


def rotate(point, angle):
    c, s = math.cos(angle), math.sin(angle)
    return c * point[0] - s * point[1], s * point[0] + c * point[1]


def application_point(state, spec):
    """Contact point on body A: rigid transform of the reference body state."""
    body = state["bodies"][spec["body_a_id"]]
    x, z = rotate(spec["local_point_a_m"], body["angle_rad"])
    return body["position_m"][0] + x, body["position_m"][1] + z


def contact_normal(state, spec):
    if spec["normal_frame"] == "WORLD":
        return spec["normal_direction"]
    frame = spec["body_a_id"] if spec["normal_frame"] == "BODY_A" else spec["body_b_id"]
    return rotate(spec["normal_direction"], state["bodies"][frame]["angle_rad"])


def support_group(spec):
    """Declared support-group identity of a contact (the submission's tagging)."""
    if spec["body_b_id"] is not None:
        return "INTERNAL"
    if spec["kind"] in FOOT_KINDS:
        return f"FOOT_{spec['side']}"
    return GROUP_FOR_KIND.get(spec["kind"], "OTHER")


def admit_reference(ref, guide):
    """Closed structural admission of reference.json before any computation."""
    times = ref.get("physics_times_s")
    require(finite_list(times, minimum=3) and all(b > a for a, b in zip(times, times[1:])),
            "REFERENCE_TIME_GRID_INVALID")
    n = len(times)
    require(all(finite_list(ref.get(k), n) for k in ("attachment_vertical_m", "vertical_momentum_kg_m_s")),
            "REFERENCE_ARRAY_MISALIGNED")
    require(all(finite_number(ref.get(k)) and ref[k] > 0 for k in ("mass_kg", "gravity_m_s2")) and
            type(ref.get("termination")) is str and type(ref.get("parameters")) is dict and
            finite_number(ref["parameters"].get("baseline_s", 1.2)), "REFERENCE_SCALAR_INVALID")
    for key in ("force_true_sample_times_s", "lpt_true_sample_times_s"):
        values = ref.get(key)
        require(finite_list(values, minimum=3) and all(b >= a for a, b in zip(values, values[1:])) and
                times[0] <= values[0] and values[-1] <= times[-1], "REFERENCE_SAMPLE_TIMES_INVALID")
    if guide:
        return {"contract": TRUTH_ADMISSION_CONTRACT, "samples": n, "contact_ids": GUIDE_CONTACTS}
    specs = ref.get("contact_specs")
    require(type(specs) is list and specs and all(type(s) is dict and type(s.get("contact_id")) is str and
            type(s.get("kind")) is str for s in specs), "REFERENCE_CONTACT_SPECS_INVALID")
    ids = [s["contact_id"] for s in specs]
    require(len(set(ids)) == len(ids), "REFERENCE_CONTACT_SPECS_INVALID")
    states, modes = ref.get("states"), ref.get("contacts")
    require(type(states) is list and len(states) == n and type(modes) is list and len(modes) == n,
            "REFERENCE_STATES_MISALIGNED")
    names = None
    for t, state, mode in zip(times, states, modes):
        require(type(state) is dict and state.get("time_s") == t and type(state.get("bodies")) is dict and
                type(state.get("contacts")) is dict, "REFERENCE_STATES_MISALIGNED")
        names = set(state["bodies"]) if names is None else names
        require(set(state["bodies"]) == names and names, "REFERENCE_STATES_MALFORMED")
        for body in state["bodies"].values():
            body_vector(body)
        contacts = state["contacts"]
        require(set(contacts) == set(ids) and all(type(c) is dict and c.get("mode") in CONTACT_MODES
                for c in contacts.values()), "REFERENCE_STATES_MALFORMED")
        require(mode == {k: c["mode"] for k, c in contacts.items()}, "REFERENCE_CONTACT_MODES_INCONSISTENT")
    for spec in specs:
        require(spec.get("body_a_id") in names and (spec.get("body_b_id") is None or spec["body_b_id"] in names)
                and finite_number(spec.get("friction_coefficient")) and spec["friction_coefficient"] >= 0,
                "REFERENCE_CONTACT_SPECS_INVALID")
        # Closed geometric spec: the application point and normal are used to
        # bind the submission's contact geometry, so they must be well formed.
        world = spec["body_b_id"] is None
        normal = spec.get("normal_direction")
        require(spec["kind"] in CONTACT_KINDS and vector2(spec.get("local_point_a_m")) and vector2(normal) and
                abs(math.hypot(*normal) - 1) <= 1e-9 and spec.get("normal_frame") in NORMAL_FRAMES and
                (vector2(spec.get("surface_point_m")) and spec["normal_frame"] == "WORLD" if world else
                 vector2(spec.get("local_point_b_m"))), "REFERENCE_CONTACT_SPECS_INVALID")
    require(type(ref.get("reference_attachment")) is dict and ref["reference_attachment"].get("body_id") in names,
            "REFERENCE_SCALAR_INVALID")
    impulses = ref.get("impulses_N_s")
    require(type(impulses) is list and all(type(i) is dict and finite_number(i.get("time_s")) and
            times[0] <= i["time_s"] <= times[-1] and i.get("contact_id") in ids and
            vector2(i.get("point_world_m")) and vector2(i.get("impulse_world_n_s")) for i in impulses) and
            all(b["time_s"] >= a["time_s"] for a, b in zip(impulses, impulses[1:])), "REFERENCE_IMPULSES_INVALID")
    return {"contract": TRUTH_ADMISSION_CONTRACT, "samples": n, "contact_ids": tuple(ids),
            "bodies": sorted(names), "specs": {s["contact_id"]: s for s in specs}}


def admit_support_ledger(truth, times, contact_ids, guide):
    """Positive-duration, grid-aligned, ordered support intervals with units."""
    with (truth / "support_intervals.csv").open(encoding="utf-8", newline="") as stream:
        reader = csv.DictReader(stream)
        require(reader.fieldnames == SUPPORT_COLUMNS, "SUPPORT_LEDGER_MALFORMED")
        raw = list(reader)
    require(raw, "SUPPORT_LEDGER_MALFORMED")
    try:
        rows = [(float(r["start_s"]), float(r["end_s"]), r["contact_id"], float(r["fx_N"]), float(r["fz_N"]))
                for r in raw]
    except (TypeError, ValueError):
        raise ReferenceRefused("SUPPORT_LEDGER_MALFORMED") from None
    require(all(math.isfinite(v) for r in rows for v in (r[0], r[1], r[3], r[4])) and
            all(r[2] in contact_ids for r in rows), "SUPPORT_LEDGER_MALFORMED")
    grid = {t: i for i, t in enumerate(times)}
    keys = []
    for start, end, contact, _, _ in rows:
        i = grid.get(start)
        # One physics interval each: rejects zero, negative and off-grid spans.
        require(i is not None and i + 1 < len(times) and times[i + 1] == end, "SUPPORT_INTERVAL_INVALID")
        keys.append((i, contact))
    require(all(b > a for a, b in zip(keys, keys[1:])), "SUPPORT_INTERVAL_INVALID")
    if guide:
        require(len(rows) == len(GUIDE_CONTACTS) * (len(times) - 1), "SUPPORT_LEDGER_COVERAGE_INCOMPLETE")
    return rows


