"""Post-generation independent SOURCE and protected-reference qualification.

This process never imports the generator. Geometry tests compare observations
to protected mechanical coordinates only after generation. Physical claims
use the existing independently authored evaluator and fixed tolerances.

Evidence admission is closed and versioned (BSMB-PAIRED-TRUTH-INVENTORY-1.0):
the SOURCE profile selects the exact expected TRUTH file set, the reference
must name the exact SOURCE manifest digest it was generated with, and absent
or incomplete evidence refuses with a typed code instead of defaulting to a
pass. Only the positively identified constrained vertical guide keeps its
deliberate analytical support and event exception. Unkeyed SHA-256 detects
accidental or partial substitution; it cannot authenticate a package whose
every authority was forged together.

Before any scientific computation, every required TRUTH file is parsed under a
closed structural schema (BSMB-PAIRED-TRUTH-ADMISSION-1.0): strict physical time
grid, aligned finite arrays, typed body/contact identities and positive,
grid-aligned support intervals. Modeled mechanics must describe the same trial
as the reference (BSMB-PAIRED-MECHANICS-BINDING-1.0): exercise, time grid,
bodies, states, contacts, support ledger and impulses. Both are serializations
of one simulated trajectory, so exact equality is required; the binding is an
identity check, the independent I2 evaluator still judges the physics.
Contact and impulse application points must equal the rigid transform of the
declared body-A point at the reference state, and each reported force must be
unilateral along the declared normal (binding 1.1). Per-body inertia has no
TRUTH authority and is reported as unbound rather than silently trusted.
"""

